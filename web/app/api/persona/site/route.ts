import { NextRequest, NextResponse } from "next/server";
import { gemmaChat, parseJson, pool, GemmaUnavailable } from "@/lib/compass/llm/gemma";
import { loadPopulation, stratifiedSample, type Resident } from "@/lib/compass/personas/population";
import { PERSONA_SYSTEM, residentBlock } from "@/lib/compass/personas/prompts";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

interface Reply {
  reaction: string;
  sentiment: number; // -2..2
  main_concern: string;
}

/** "Who lives here?" — 3 residents of the area react to a building-level change. */
export async function POST(req: NextRequest) {
  const { areaId, areaName, building, change, seed = 1 } = await req.json();
  let pop: Resident[];
  try {
    pop = await loadPopulation(areaId);
  } catch {
    return NextResponse.json({ error: `No synthetic population for ${areaName ?? areaId} (census suppresses very small areas).` }, { status: 404 });
  }
  const isHome = !!building?.hdb;
  const panel = stratifiedSample(pop, 3, seed, isHome ? (r) => r.dwelling.startsWith("HDB") : undefined);
  const facts = [
    `Building: ${isHome ? "an HDB residential block" : "a building"} in ${areaName}, about ${building?.floors ?? "?"} storeys, roof ${Math.round(building?.footprintM2 ?? 0)} m².`,
    `Proposed change: ${change?.label ?? "rooftop solar"}.`,
    ...(change?.facts ?? []).map((f: string) => `- ${f}`),
    isHome ? "The resident lives in this block." : "The resident lives in the surrounding area and uses this building occasionally.",
  ].join("\n");
  try {
    const out = await pool(panel, 3, async (r) => {
      const res = await gemmaChat(
        [
          { role: "system", content: PERSONA_SYSTEM },
          {
            role: "user",
            content: `${residentBlock(r)}\n\nFacts (from the HELIOS engine):\n${facts}\n\nHow does this resident react? JSON: {"reaction": string, "sentiment": integer -2..2, "main_concern": string (max 8 words)}`,
          },
        ],
        { json: true, maxTokens: 220, temperature: 0.7 }
      );
      const j = parseJson<Reply>(res.text);
      return { resident: r, ...j, ms: res.ms };
    });
    return NextResponse.json({ panel: out, model: "Gemma 4 26B-A4B (local)", note: "Synthetic residents sampled from GHS 2025; voices generated by Gemma from the facts shown." });
  } catch (e: any) {
    const status = e instanceof GemmaUnavailable ? 503 : 500;
    return NextResponse.json({ error: e?.message ?? String(e) }, { status });
  }
}
