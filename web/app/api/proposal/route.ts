import { NextRequest } from "next/server";
import { getTariff } from "@/lib/finance";

export const runtime = "nodejs";
export const maxDuration = 60;

const GEMINI_KEY = process.env.GEMINI_API_KEY ?? "";

const PROPOSAL_PROMPT_TEMPLATE = (
  audience: string,
  solarJson: string,
  provenance: string,
  provenanceShort: string,
  utility: string,
  country: string,
  verifiedPolicy: string
) => `You are HELIO Scout, an AI pre-feasibility advisor for rooftop solar.

Write a sharp pre-feasibility proposal for the building below.
Audience: ${audience}.

BUILDING DATA (verified from ${provenance}):
${solarJson}

VERIFIED POLICY (the ONLY policy text you may cite):
${verifiedPolicy}

STRICT RULES — read carefully:
- You may ONLY use numbers that appear in the BUILDING DATA JSON above. Do not invent tariffs, incentives, payback figures, or any other quantitative claim that is not in that JSON.
- You may ONLY cite the policy text in the VERIFIED POLICY block. If that block is empty, do not name any specific policy, decree, or programme — speak generically about "local renewable energy frameworks" instead.
- This is a PRE-FEASIBILITY report, not a bankable design. Use the phrase "pre-feasibility estimate" at least once. If confidence_tier is "B", explicitly mention the ±confidence_band_pct% uncertainty band.
- Cite the local utility by name (${utility}).

OUTPUT FORMAT
- 5 short sections, each with a bold one-line header in Markdown (##).
- Section order:
  1. ## Executive Summary  (2 sentences, the headline number + confidence framing)
  2. ## System Specification  (panels, kWp, roof area, yield — pull from JSON)
  3. ## Financial Case  (annual savings, simple payback, NPV at 8% discount, LCOE — pull from JSON)
  4. ## Climate Impact  (CO₂ offset and grid-displacement framing)
  5. ## Next Steps  (3 bullet actions, this week / this month / this quarter)
- Tone: confident but honest. ~280 words total.
- End with one closing line: "Generated by HELIO Scout · ${provenanceShort} + Gemini 2.5 Flash".
`;

function splitForTypewriter(text: string): string[] {
  const out: string[] = [];
  let cur = "";
  for (const ch of text) {
    cur += ch;
    if (" \n.,;:!?".includes(ch)) {
      out.push(cur);
      cur = "";
    }
  }
  if (cur) out.push(cur);
  return out;
}

export async function POST(req: NextRequest) {
  const { solar, audience = "building_owner" } = await req.json();
  const provenance = solar?.provenance ?? "Google Solar API";
  const provenanceShort =
    solar?.source === "google_solar"
      ? "Google Solar API"
      : "Gemini Vision + Static Maps";
  const countryCode = solar?.country_code ?? "DEFAULT";
  const verifiedPolicy =
    getTariff(countryCode).verified_policy ||
    "(no verified policy provided — do not invent one)";

  const prompt = PROPOSAL_PROMPT_TEMPLATE(
    audience,
    JSON.stringify(solar, null, 2),
    provenance,
    provenanceShort,
    solar?.utility ?? "the local utility",
    solar?.country ?? "the region",
    verifiedPolicy
  );

  const url =
    "https://generativelanguage.googleapis.com/v1beta/models/" +
    `gemini-2.5-flash:streamGenerateContent?alt=sse&key=${GEMINI_KEY}`;
  const body = {
    contents: [{ role: "user", parts: [{ text: prompt }] }],
    generationConfig: { temperature: 0.75, maxOutputTokens: 1400 },
  };

  const encoder = new TextEncoder();
  const stream = new ReadableStream({
    async start(controller) {
      const emit = async (chunk: string) => {
        controller.enqueue(encoder.encode(chunk));
        // tiny await to let the runtime flush
        await new Promise((r) => setTimeout(r, 12));
      };
      try {
        const upstream = await fetch(url, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(body),
        });
        if (!upstream.ok || !upstream.body) {
          const err = await upstream.text();
          await emit(
            `data: ${JSON.stringify({ error: err.slice(0, 500) })}\n\n`
          );
          controller.close();
          return;
        }
        const reader = upstream.body.getReader();
        const decoder = new TextDecoder();
        let buf = "";
        const buffered: string[] = [];
        while (true) {
          const { value, done } = await reader.read();
          if (done) break;
          buf += decoder.decode(value, { stream: true });
          const lines = buf.split("\n");
          buf = lines.pop() ?? "";
          for (const rawLine of lines) {
            const line = rawLine.trim();
            if (!line.startsWith("data: ")) continue;
            const payload = line.slice(6);
            if (payload === "[DONE]") continue;
            try {
              const obj = JSON.parse(payload);
              const parts =
                obj?.candidates?.[0]?.content?.parts ?? [];
              for (const p of parts) {
                const txt = p.text ?? "";
                if (!txt) continue;
                buffered.push(txt);
                while (true) {
                  const full = buffered.join("");
                  const chunks = splitForTypewriter(full);
                  if (chunks.length <= 1) break;
                  for (const c of chunks.slice(0, -1)) {
                    await emit(
                      `data: ${JSON.stringify({ text: c })}\n\n`
                    );
                  }
                  buffered.length = 0;
                  buffered.push(chunks[chunks.length - 1]);
                }
              }
            } catch {
              /* ignore parse errors */
            }
          }
        }
        const remainder = buffered.join("");
        for (const c of splitForTypewriter(remainder)) {
          await emit(`data: ${JSON.stringify({ text: c })}\n\n`);
        }
        await emit("data: [DONE]\n\n");
      } catch (e: any) {
        controller.enqueue(
          encoder.encode(
            `data: ${JSON.stringify({ error: e?.message ?? "stream error" })}\n\n`
          )
        );
      } finally {
        controller.close();
      }
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "text/event-stream",
      "Cache-Control": "no-cache, no-transform",
      Connection: "keep-alive",
    },
  });
}
