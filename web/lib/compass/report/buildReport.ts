// Generic intervention feasibility report builder.
//
// Given a located intervention (EV site is the proof-of-concept type, but the
// shape is generic), it assembles a takeaway report: real imagery, an AI visual
// feasibility read, a photorealistic "after", plus whatever computational /
// civic / scenario numbers the caller passes in. Images + JSON are cached under
// public/reports/<id>/ so the demo runs off frozen files — no live API on stage.

import {readReportAsset,writeReportAsset,reportLocation} from "@/lib/cloud/reports";
import {
  streetViewAt,
  assessSiting,
  renderAfter,
  type InterventionSpec,
  type SitingAssessment,
} from "./imagery";
import { fetchSatelliteTile } from "@/lib/vision";

export interface ReportInput {
  id: string;
  spec: InterventionSpec;
  lat: number;
  lng: number;
  /** computational feasibility (from the recommender / engine). */
  computational?: { score?: number; reasons?: string[]; assetSpec?: Record<string, unknown> };
  /** optional public-pulse block (civicFor result, already resolved). */
  civic?: unknown;
  /** optional impact numbers (from a scenario run). */
  impact?: { cumulativeCO2AvoidedTonnes?: number; costPerTonneUsd?: number | null; horizonYears?: number };
}

export interface InterventionReport {
  id: string;
  title: string;
  generatedAtNote: string;
  location: { lat: number; lng: number };
  images: { before?: string; after?: string; satellite?: string };
  siting: SitingAssessment | null;
  computational?: ReportInput["computational"];
  civic?: unknown;
  impact?: ReportInput["impact"];
  labels: string[];
  status: "full" | "partial" | "cached";
}

const HEADINGS = [0, 90, 180, 270];

async function readCached(id: string): Promise<InterventionReport | null> {
  const bytes = await readReportAsset(id, "report.json");
  if (!bytes) return null;
  const r = JSON.parse(bytes.toString()) as InterventionReport;
  r.status = "cached";
  for (const key of ["before", "after", "satellite"] as const) {
    const url=r.images[key];
    if(url?.startsWith(`/reports/${id}/`)) r.images[key]=url.replace("/reports/", "/api/reports/");
  }
  return r;
}

/**
 * Build (or read cached) the report. Pass forceRegen to rebuild.
 * The pitch reads the cache; the live button can forceRegen but must degrade
 * gracefully if Gemini/Maps fail (report is still returned with whatever we got).
 */
export async function buildReport(
  input: ReportInput,
  opts: { mapsKey: string; geminiKey: string; forceRegen?: boolean } = { mapsKey: "", geminiKey: "" }
): Promise<InterventionReport> {
  if (!opts.forceRegen) {
    const cached = await readCached(input.id);
    if (cached) return cached;
  }

  reportLocation(input.id, "report.json");

  const rel = (f: string) => `/api/reports/${input.id}/${f}`;
  const images: InterventionReport["images"] = {};
  let siting: SitingAssessment | null = null;
  let status: InterventionReport["status"] = "partial";

  // 1. Street View — try headings until one returns real imagery.
  let street: Buffer | null = null;
  if (opts.mapsKey) {
    for (const h of HEADINGS) {
      street = await streetViewAt(input.lat, input.lng, opts.mapsKey, h);
      if (street) break;
    }
    if (street) {
      await writeReportAsset(input.id, "before.jpg", street);
      images.before = rel("before.jpg");
    }
  }

  // 2. Satellite tile.
  let sat: Buffer | null = null;
  let groundSideM = 0;
  if (opts.mapsKey) {
    const tile = await fetchSatelliteTile(input.lat, input.lng, opts.mapsKey, 19, 640);
    if (tile) {
      sat = tile.pngBytes;
      groundSideM = tile.groundSideM;
      await writeReportAsset(input.id, "satellite.png", sat);
      images.satellite = rel("satellite.png");
    }
  }

  // 3. Visual feasibility (needs at least the street image).
  if (street && opts.geminiKey) {
    siting = await assessSiting(street, sat, groundSideM, input.spec, opts.geminiKey);
  }

  // 4. After-image (render the intervention into the real photo).
  if (street && opts.geminiKey) {
    const after = await renderAfter(street, input.spec, siting?.bestPlacement ?? "", opts.geminiKey);
    if (after) {
      await writeReportAsset(input.id, "after.png", after);
      images.after = rel("after.png");
    }
  }

  if (images.before && images.after && siting) status = "full";

  const report: InterventionReport = {
    id: input.id,
    title: input.spec.title,
    generatedAtNote: "Generated by HELIO — desk study on frozen data + AI imagery",
    location: { lat: input.lat, lng: input.lng },
    images,
    siting,
    computational: input.computational,
    civic: input.civic,
    impact: input.impact,
    labels: [
      "AI visual estimate — desk study, not a site survey",
      "AI visualization — illustrative, not an engineering drawing",
    ],
    status,
  };

  await writeReportAsset(input.id, "report.json", JSON.stringify(report, null, 1));
  return report;
}
